export function spritePath(sprite: readonly string[]): string {
  let d = ''
  sprite.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') d += `M${x} ${y}h1v1h-1z`
    }
  })
  return d
}
